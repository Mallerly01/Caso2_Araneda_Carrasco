CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(30),
    email VARCHAR(160) NOT NULL,
    CONSTRAINT uk_clientes_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS veterinarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    especialidad VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    especie VARCHAR(60) NOT NULL,
    raza VARCHAR(80),
    fecha_nacimiento DATE NOT NULL,
    peso DECIMAL(6,2) NOT NULL,
    CONSTRAINT fk_mascotas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);

CREATE TABLE IF NOT EXISTS reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    veterinario_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_reservas_mascota FOREIGN KEY (mascota_id) REFERENCES mascotas(id),
    CONSTRAINT fk_reservas_veterinario FOREIGN KEY (veterinario_id) REFERENCES veterinarios(id)
);

CREATE TABLE IF NOT EXISTS atenciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    diagnostico VARCHAR(500) NOT NULL,
    tratamiento VARCHAR(500) NOT NULL,
    medicamentos VARCHAR(500),
    fecha_registro TIMESTAMP NOT NULL,
    CONSTRAINT fk_atenciones_reserva FOREIGN KEY (reserva_id) REFERENCES reservas(id),
    CONSTRAINT uk_atenciones_reserva UNIQUE (reserva_id)
);

CREATE INDEX IF NOT EXISTS idx_mascotas_cliente ON mascotas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_reservas_veterinario_fecha ON reservas(veterinario_id, fecha, hora);
CREATE INDEX IF NOT EXISTS idx_reservas_mascota ON reservas(mascota_id);
